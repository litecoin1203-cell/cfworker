"""Licence texts of the Go modules compiled into AndroidLibXrayLite's libgojni.so.

The APK carries libgojni.so (Xray-core and its Go dependencies). Their licences must ship with it, and
Flutter's own NOTICES only cover Dart packages, so this tool keeps assets/licenses/go-modules.txt, which
lib/licenses.dart registers with Flutter's LicenseRegistry (Profile > Open-source licences).

Run from flutter_vpn/ with Go on PATH (it reads the build info with `go version -m`):

  python3 -I tool/go_licenses.py write <path/to/libgojni.so>   # refresh the asset after an AAR bump
  python3 -I tool/go_licenses.py check <path/to/libgojni.so>   # CI: fail when the asset is stale

`write` downloads each module at its exact version from proxy.golang.org and keeps its LICENSE / COPYING /
NOTICE / PATENTS files from the module root. A `=>` replacement in the build info is followed, so the text
is the one of the code that was really compiled.
"""
import io, os, re, subprocess, sys, urllib.request, zipfile

ASSET = os.path.join('assets', 'licenses', 'go-modules.txt')
HEADER = '==== module '
WANTED = re.compile(r'^(licen[cs]e|copying|notice|patents)(\.md|\.txt)?$', re.I)


def modules(lib):
    """(path, version) of every module in the binary, after replacements; and the Go version."""
    out = subprocess.run(['go', 'version', '-m', lib], check=True, capture_output=True, text=True).stdout
    first, *rest = out.splitlines()
    go = first.split(':', 1)[1].strip()
    mods = []
    for line in rest:
        p = line.split()
        if not p:
            continue
        if p[0] == 'dep':
            mods.append([p[1], p[2]])
        elif p[0] == '=>' and mods:
            mods[-1] = [p[1], p[2]]
    # the library itself is a local path in its own build (no published version)
    return go, sorted((m, v) for m, v in mods if not m.startswith('/') and v != '(devel)'
                      and not v.startswith('v0.0.0-00010101000000'))


def escape(path):
    return re.sub(r'[A-Z]', lambda m: '!' + m.group(0).lower(), path)


def texts(mod, ver):
    url = f'https://proxy.golang.org/{escape(mod)}/@v/{escape(ver)}.zip'
    with urllib.request.urlopen(url, timeout=120) as r:
        z = zipfile.ZipFile(io.BytesIO(r.read()))
    root = f'{mod}@{ver}/'
    found = []
    for name in sorted(z.namelist()):
        if name.startswith(root) and '/' not in name[len(root):] and WANTED.match(name[len(root):]):
            found.append((name[len(root):], z.read(name).decode('utf-8', 'replace').strip('\n')))
    if not any(n.lower().startswith(('licen', 'copying')) for n, _ in found):
        sys.exit(f'{mod}@{ver}: no licence file in the module root; add it by hand')
    return found


def listed():
    with open(ASSET, encoding='utf-8') as f:
        return sorted(tuple(l[len(HEADER):].split()) for l in f if l.startswith(HEADER)
                      and not l.startswith(HEADER + 'std '))


def write(lib):
    go, mods = modules(lib)
    goroot = subprocess.run(['go', 'env', 'GOROOT'], check=True, capture_output=True, text=True).stdout.strip()
    with open(os.path.join(goroot, 'LICENSE'), encoding='utf-8') as f:
        std = f.read().strip('\n')
    parts = [
        'Go modules compiled into libgojni.so (AndroidLibXrayLite, see SOURCE.txt), as listed by\n'
        '`go version -m`. Generated by tool/go_licenses.py; do not edit by hand.\n',
        f'{HEADER}std {go}\n-- LICENSE\n{std}\n',
    ]
    for mod, ver in mods:
        body = ''.join(f'-- {n}\n{t}\n' for n, t in texts(mod, ver))
        parts.append(f'{HEADER}{mod} {ver}\n{body}')
        print(f'{mod} {ver}')
    with open(ASSET, 'w', encoding='utf-8') as f:
        f.write('\n'.join(parts))


def check(lib):
    _, mods = modules(lib)
    have = listed()
    if have != mods:
        print('assets/licenses/go-modules.txt does not match the Go modules in', lib)
        for m in sorted(set(mods) - set(have)):
            print('  missing:', *m)
        for m in sorted(set(have) - set(mods)):
            print('  not in the binary:', *m)
        print('Run: python3 -I tool/go_licenses.py write', lib)
        sys.exit(1)
    print(f'go-modules.txt lists all {len(mods)} Go modules of {lib}')


if __name__ == '__main__':
    if len(sys.argv) != 3 or sys.argv[1] not in ('write', 'check'):
        sys.exit(__doc__)
    {'write': write, 'check': check}[sys.argv[1]](sys.argv[2])
