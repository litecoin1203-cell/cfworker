const DEFAULT = { name: '', c1: '#283FFF', c2: '#3C2BD0' };

export const cardDigits = (v) => String(v || '').replace(/[۰-۹]/g, (d) => '۰۱۲۳۴۵۶۷۸۹'.indexOf(d)).replace(/\D/g, '');

export function bankOf(card) {
  const d = cardDigits(card);
  const hit = BANKS.find(([bin]) => d.startsWith(bin));
  return hit ? { name: hit[1], c1: hit[2], c2: hit[3] } : DEFAULT;
}

export function luhnOk(card) {
  const d = cardDigits(card);
  if (d.length !== 16) return false;
  let sum = 0;
  for (let i = 0; i < 16; i++) {
    let n = +d[15 - i];
    if (i % 2 === 1) { n *= 2; if (n > 9) n -= 9; }
    sum += n;
  }
  return sum % 10 === 0;
}
